/*
断点打在 `d()` 里时，`c()` 已经跑完并返回了，所以栈上没有它。

调用顺序是：`main → a → b → c`，`c` 立刻返回，然后 `b` 再调 `d`。调用栈只记录**还没返回的函数**，不是历史记录：

```
d      ← 当前停在这
b      ← 还在等 d 返回
a
main
```

`c` 进过栈，但已经出栈了。若想在栈上看到 `c`，把断点打在 `c()` 函数体里面。

*/


void d()
{ // here
}

void c()
{
}

void b()
{
	c();
	d();
}

void a()
{
	b();
}

int main()
{
	a();

	return 0;
}